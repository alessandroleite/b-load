"""
data_generation.py — Synthetic experiment data generation via R.

Experimental datasets (DAGs + linear SEM samples) are generated by calling R
helper functions defined in ``generate_data.R`` at the project root, via
``rpy2``.  Results are cached to disk so that the same seed/parameter
combination always reproduces the same dataset.

The R script is sourced automatically when this module is imported.  If
``generate_data.R`` is not found, an :class:`FileNotFoundError` is raised at
import time.
"""

import json
import pickle
from pathlib import Path

import networkx as nx
import numpy as np
from rpy2 import robjects
from rpy2.robjects import r


def save_data(data: dict, seed: int, **kwargs) -> None:
    """
    Persist an experiment dictionary to disk under a path derived from the
    generation parameters.

    The file is saved at ``experiments/<json_kwargs>/<seed>.pkl``.  Parent
    directories are created automatically.

    Args:
        data (dict): Experiment dictionary to serialise (must be picklable).
        seed (int): Random seed used to generate the data.
        **kwargs: All other generation parameters (used to build the directory
            name).
    """
    file_path = Path("experiments/{}/{}.pkl".format(json.dumps(kwargs), seed))
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with file_path.open("wb") as file:
        pickle.dump(data, file)


def load_data(seed: int, **kwargs) -> dict:
    """
    Load a previously cached experiment dictionary from disk.

    Raises :class:`FileNotFoundError` if no cached file exists for the given
    seed/parameter combination (the caller should then generate fresh data).

    Args:
        seed (int): Random seed used to generate the data.
        **kwargs: Generation parameters (used to reconstruct the file path).

    Returns:
        dict: The loaded experiment dictionary.
    """
    file_path = Path("experiments/{}/{}.pkl".format(json.dumps(kwargs), seed))
    with file_path.open("rb") as file:
        return pickle.load(file)


def generate_data(
    seed: int,
    observed: int,
    exp_degree: float,
    max_degree: int,
    targets: int,
    latent: int = 0,
    connected: bool = True,
    expl_anc: bool = False,
    identifiable: bool = False,
    min_adj_size: int = 0,
    samples_num: int = 0,
    discrete: bool = False,
    max_classes: int = 2,
    file: str | None = None,
    save: bool = True,
) -> dict:
    """
    Generate (or load from cache) a synthetic experiment dataset.

    If a cached file exists for the given parameters, it is loaded and returned
    immediately.  Otherwise, the R helper function ``generate_data`` (or
    ``generate_data_from_file`` when ``file`` is given) is called via ``rpy2``
    to produce a random linear Gaussian SEM, a DAG sample, and observations.

    Args:
        seed (int): Random seed for the R and Python RNGs.
        observed (int): Number of observed (non-latent) nodes.
        exp_degree (float): Expected degree of the generated random graph.
        max_degree (int): Maximum node degree allowed in the graph.
        targets (int): Number of treatment–outcome target pairs to sample.
        latent (int): Number of latent (hidden) nodes.
        connected (bool): If ``True``, only accept connected graphs.
        expl_anc (bool): If ``True``, require the targets to form an explicit
            ancestor–descendant pair in the generated DAG.
        identifiable (bool): If ``True``, require the causal effect to be
            identifiable from the generated CPDAG.
        min_adj_size (int): Minimum size of the true optimal adjustment set.
        samples_num (int): Number of i.i.d. observations to draw.
        discrete (bool): If ``True``, generate discrete (binary/categorical)
            data instead of continuous Gaussian data.
        max_classes (int): Maximum number of categories per discrete variable
            (only used when ``discrete=True``).
        file (str | None): Path to an existing R model file.  When provided,
            the graph structure is loaded from that file and only new samples
            are drawn (``generate_data_from_file`` is called).
        save (bool): If ``True``, cache the generated dataset to disk.

    Returns:
        dict with keys:

        * ``"id"`` — experiment identifier.
        * ``"data"`` (np.ndarray) — observation matrix (n_samples × n_nodes).
        * ``"targets"`` (np.ndarray) — 0-based indices of the target nodes.
        * ``"true_dag"`` (nx.DiGraph) — ground-truth DAG with edge weights
          equal to the linear SEM coefficients.
        * ``"cpt"`` — R conditional-probability table object (for binary data).
        * ``"treatment"`` (int) — 0-based index of the treatment node.
        * ``"outcome"`` (int) — 0-based index of the outcome node.
    """
    if file is None:
        gen_func = r["generate_data"]
        kwargs = {
            "seed": seed,
            "observed": observed,
            "latent": latent,
            "exp_degree": exp_degree,
            "max_degree": max_degree,
            "targets": targets,
            "connected": connected,
            "expl_anc": expl_anc,
            "identifiable": identifiable,
            "min_adj_size": min_adj_size,
            "samples_num": samples_num,
            "discrete": discrete,
            "max_classes": max_classes,
        }
    else:
        gen_func = r["generate_data_from_file"]
        kwargs = {
            "file": file,
            "seed": seed,
            "targets": targets,
            "identifiable": identifiable,
            "min_adj_size": min_adj_size,
            "samples_num": samples_num,
        }

    try:
        return load_data(**kwargs)
    except FileNotFoundError:
        r_data = gen_func(**kwargs)
        true_dag = r_data.rx2("suffStat").rx2("g")
        true_dag = nx.from_numpy_array(
            np.array(r["as"](true_dag, "matrix")),
            create_using=nx.DiGraph,
        )
        dm = np.array(r_data.rx2("suffStat").rx2("dm"))
        data = {
            "id": r_data.rx2("id")[0],
            "data": dm,
            "targets": np.array(r_data.rx2("targets")).astype(np.int32) - 1,
            "true_dag": true_dag,
            "cpt": r_data.rx2("cpt"),
            "treatment": np.array(r_data.rx2("treatment")).astype(np.int32)[0] - 1,
            "outcome": np.array(r_data.rx2("outcome")).astype(np.int32)[0] - 1,
        }
        if save:
            save_data(data, **kwargs)
        return data


# ---------------------------------------------------------------------------
# Module initialisation — source the R data-generation script
# ---------------------------------------------------------------------------

_r_script = Path(__file__).resolve().parent.parent / "generate_data.R"

if _r_script.exists():
    robjects.r.source(str(_r_script))
    print(f"Successfully sourced: {_r_script}")
else:
    raise FileNotFoundError(f"R data generation script not found at {_r_script}")
